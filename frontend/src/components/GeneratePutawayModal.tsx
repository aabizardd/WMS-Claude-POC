import { useEffect, useState } from 'react';
import SearchableSelect from './SearchableSelect';
import type { BinOption, GoodsReceiveItem } from '../types';

export interface PutawayLine {
  itemId: string;
  plannedQty: number;
  binId: string;
  /** Optional, as on WMS dev. */
  pickerId?: number;
}

interface RowForm {
  selected: boolean;
  plannedQty: number;
  binId: string;
  pickerId: string;
}

interface Props {
  open: boolean;
  grNumber: string;
  /** The Goods Receive lines that still have something to put away. */
  items: GoodsReceiveItem[];
  bins: BinOption[];
  pickers: { id: number; name: string }[];
  loadingOptions?: boolean;
  submitting: boolean;
  error?: string;
  onClose: () => void;
  onSubmit: (lines: PutawayLine[]) => void;
}

const fmt = (n: number) => n.toLocaleString(undefined, { maximumFractionDigits: 4 });

/**
 * Generate Putaway — laid out like WMS dev's: the putaway id (generated by
 * the system), then the Material List where each material gets its planned
 * qty, Destination Location (bin, required) and Picker. The table's first row
 * sets one picker for every material, as in Generate Picking.
 */
export default function GeneratePutawayModal({
  open,
  grNumber,
  items,
  bins,
  pickers,
  loadingOptions,
  submitting,
  error,
  onClose,
  onSubmit,
}: Props) {
  const [rows, setRows] = useState<Record<string, RowForm>>({});
  const [pickerForAll, setPickerForAll] = useState('');
  const [localError, setLocalError] = useState('');

  // Fresh form each time the modal opens: every line ticked, its whole remaining planned.
  useEffect(() => {
    if (!open) return;
    setLocalError('');
    setPickerForAll('');
    setRows(
      Object.fromEntries(
        items.map((it) => [
          it.id,
          { selected: true, plannedQty: it.qty_remaining, binId: '', pickerId: '' },
        ]),
      ),
    );
    // Rebuilt per opening; `items` is the parent's current GR.
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [open]);

  useEffect(() => {
    if (!open) return;
    const onKey = (e: KeyboardEvent) => e.key === 'Escape' && !submitting && onClose();
    document.addEventListener('keydown', onKey);
    return () => document.removeEventListener('keydown', onKey);
  }, [open, submitting, onClose]);

  if (!open) return null;

  const selected = items.filter((it) => rows[it.id]?.selected);
  const allSelected = items.length > 0 && selected.length === items.length;
  const missingBin = selected.some((it) => !rows[it.id]?.binId);
  const totalPlanned = selected.reduce((s, it) => s + (Number(rows[it.id]?.plannedQty) || 0), 0);
  const binOptions = bins.map((b) => ({ value: b.id, label: b.binLabel || b.binCode }));
  const pickerOptions = pickers.map((p) => ({ value: String(p.id), label: p.name }));

  function patch(id: string, p: Partial<RowForm>) {
    setRows((r) => ({ ...r, [id]: { ...r[id], ...p } }));
  }
  function setAll(p: Partial<RowForm>) {
    setRows((r) => Object.fromEntries(Object.entries(r).map(([id, row]) => [id, { ...row, ...p }])));
  }

  function submit() {
    setLocalError('');
    if (selected.length === 0) {
      setLocalError('Select at least one material.');
      return;
    }
    const lines: PutawayLine[] = [];
    for (const it of selected) {
      const r = rows[it.id];
      const label = it.material_code ?? it.item_name ?? '—';
      const qty = Number(r.plannedQty);
      if (!(qty > 0)) {
        setLocalError(`Planned qty must be greater than 0 for ${label}.`);
        return;
      }
      if (qty > it.qty_remaining + 1e-9) {
        setLocalError(`Planned qty (${qty}) exceeds remaining (${it.qty_remaining}) for ${label}.`);
        return;
      }
      if (!r.binId) {
        setLocalError('Please select Destination Bin for all selected materials.');
        return;
      }
      lines.push({
        itemId: it.id,
        plannedQty: qty,
        binId: r.binId,
        pickerId: r.pickerId ? Number(r.pickerId) : undefined,
      });
    }
    onSubmit(lines);
  }

  const shownError = localError || error;
  const th =
    'sticky top-0 z-10 whitespace-nowrap border-b border-neutral-200 bg-neutral-50 px-3 py-2.5 text-left text-xs font-semibold uppercase tracking-wide text-neutral-500 dark:border-slate-700 dark:bg-slate-900 dark:text-slate-400';
  const td = 'border-b border-neutral-100 px-3 py-3 align-middle dark:border-slate-700/70';
  const checkbox = 'h-4 w-4 rounded border-neutral-300 text-[#5166AE] focus:ring-[#5166AE]';

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center p-4">
      <div
        className="absolute inset-0 bg-slate-900/50 backdrop-blur-[2px]"
        onClick={() => !submitting && onClose()}
      />
      <div
        role="dialog"
        aria-modal="true"
        aria-labelledby="gen-putaway-title"
        className="relative z-10 flex max-h-[90vh] w-full max-w-[1100px] flex-col overflow-hidden rounded-2xl border border-neutral-200 bg-white shadow-[0_22px_60px_rgba(15,23,42,0.32)] dark:border-slate-700 dark:bg-slate-800"
      >
        {/* Header */}
        <div className="flex shrink-0 items-start justify-between gap-4 border-b border-neutral-200 px-6 py-5 dark:border-slate-700">
          <div>
            <h2 id="gen-putaway-title" className="text-2xl font-semibold leading-snug text-neutral-900 dark:text-white">
              Generate Putaway{' '}
              <span className="text-lg font-normal text-neutral-500">({grNumber})</span>
            </h2>
            <p className="mt-1 text-[13px] text-neutral-500 dark:text-slate-400">
              Set the planned quantity, destination bin and picker for each material.
            </p>
          </div>
          <button
            type="button"
            onClick={onClose}
            disabled={submitting}
            className="rounded-lg p-1.5 text-neutral-400 hover:bg-neutral-100 hover:text-neutral-700 dark:hover:bg-slate-700"
            aria-label="Close"
          >
            <svg className="h-5 w-5" fill="none" stroke="currentColor" strokeWidth={2} viewBox="0 0 24 24">
              <path strokeLinecap="round" d="M6 18L18 6M6 6l12 12" />
            </svg>
          </button>
        </div>

        {/* Body */}
        <div className="flex-1 space-y-5 overflow-y-auto px-6 py-5">
          {shownError && (
            <div className="flex items-start gap-2 rounded-lg border border-red-200 bg-red-50 px-3 py-2.5 text-sm text-red-700">
              <svg className="mt-0.5 h-4 w-4 shrink-0" fill="none" stroke="currentColor" strokeWidth={2} viewBox="0 0 24 24">
                <circle cx="12" cy="12" r="10" />
                <path strokeLinecap="round" d="M12 8v4M12 16h.01" />
              </svg>
              {shownError}
            </div>
          )}

          <div className="max-w-sm">
            <div className="mb-1 text-xs font-medium text-neutral-600 dark:text-slate-400">Putaway ID</div>
            <div className="flex h-9 items-center rounded-lg border border-neutral-200 bg-neutral-50 px-3 text-sm italic text-neutral-500 dark:border-slate-600 dark:bg-slate-900/40">
              Generated by System
            </div>
          </div>

          {/* Material List */}
          <section className="overflow-hidden rounded-xl border border-neutral-200 shadow-sm dark:border-slate-700">
            <div className="flex flex-wrap items-center justify-between gap-2 border-b border-neutral-200 bg-white px-4 py-3 dark:border-slate-700 dark:bg-slate-800">
              <div className="flex items-center gap-2">
                <h3 className="text-base font-semibold text-neutral-900 dark:text-white">Material List</h3>
                <span className="rounded-full bg-[#E1E4F8] px-2 py-0.5 text-xs font-semibold text-[#5166AE] dark:bg-[#5166AE]/25 dark:text-[#c7cff0]">
                  {selected.length} of {items.length} selected
                </span>
              </div>
              <span className="text-xs text-neutral-500">
                Total planned <span className="font-semibold text-neutral-800 dark:text-slate-100">{fmt(totalPlanned)}</span>
              </span>
            </div>

            {items.length === 0 ? (
              <div className="py-12 text-center text-sm text-neutral-400">
                No materials with remaining quantity to put away.
              </div>
            ) : (
              <div className="max-h-[56vh] overflow-auto">
                <table className="w-full min-w-[1000px] border-separate border-spacing-0 text-sm">
                  <thead>
                    <tr>
                      <th className={`${th} w-10`}>
                        <input
                          type="checkbox"
                          aria-label="Select all materials"
                          className={checkbox}
                          checked={allSelected}
                          onChange={(e) => setAll({ selected: e.target.checked })}
                        />
                      </th>
                      <th className={`${th} w-12`}>No</th>
                      <th className={th}>Material</th>
                      <th className={th}>UoM</th>
                      <th className={`${th} text-right`}>Remaining</th>
                      <th className={`${th} w-28`}>
                        Planned Qty <span className="text-red-500">*</span>
                      </th>
                      <th className={`${th} w-60`}>
                        Destination Location <span className="text-red-500">*</span>
                      </th>
                      <th className={`${th} w-56`}>Picker</th>
                    </tr>
                  </thead>
                  <tbody>
                    {/* Picker for all items — fills the Picker of every row below. */}
                    <tr className="bg-[#F5F6FD] dark:bg-[#5166AE]/10">
                      <td colSpan={7} className="border-b border-[#E1E4F8] px-3 py-3 dark:border-[#5166AE]/30">
                        <div className="flex items-center gap-3">
                          <span className="flex h-8 w-8 shrink-0 items-center justify-center rounded-lg bg-[#E1E4F8] text-[#5166AE] dark:bg-[#5166AE]/30 dark:text-[#c7cff0]">
                            <svg className="h-4 w-4" fill="none" stroke="currentColor" strokeWidth={2} strokeLinecap="round" strokeLinejoin="round" viewBox="0 0 24 24">
                              <path d="M16 21v-2a4 4 0 0 0-4-4H6a4 4 0 0 0-4 4v2" />
                              <circle cx="9" cy="7" r="4" />
                              <path d="M22 21v-2a4 4 0 0 0-3-3.87M16 3.13a4 4 0 0 1 0 7.75" />
                            </svg>
                          </span>
                          <div>
                            <div className="text-sm font-semibold text-[#3F4F8C] dark:text-[#c7cff0]">Picker for all items</div>
                            <div className="text-xs text-neutral-500">
                              Pick one here to assign it to all {items.length} materials — any row can still be changed.
                            </div>
                          </div>
                        </div>
                      </td>
                      <td className="border-b border-[#E1E4F8] px-3 py-3 dark:border-[#5166AE]/30">
                        <SearchableSelect
                          value={pickerForAll}
                          onChange={(v) => {
                            setPickerForAll(v);
                            setAll({ pickerId: v });
                          }}
                          placeholder={loadingOptions ? 'Loading…' : 'Assign to all…'}
                          searchPlaceholder="Search picker…"
                          options={pickerOptions}
                        />
                      </td>
                    </tr>

                    {items.map((it, i) => {
                      const r = rows[it.id];
                      if (!r) return null;
                      const over = (Number(r.plannedQty) || 0) > it.qty_remaining + 1e-9;
                      return (
                        <tr
                          key={it.id}
                          className={`transition-colors ${
                            r.selected
                              ? 'bg-white hover:bg-neutral-50/80 dark:bg-slate-800 dark:hover:bg-slate-700/40'
                              : 'bg-neutral-50/70 text-neutral-400 dark:bg-slate-900/40'
                          }`}
                        >
                          <td className={td}>
                            <input
                              type="checkbox"
                              aria-label={`Select ${it.material_code ?? it.item_name ?? 'material'}`}
                              className={checkbox}
                              checked={r.selected}
                              onChange={(e) => patch(it.id, { selected: e.target.checked })}
                            />
                          </td>
                          <td className={`${td} text-neutral-400`}>{i + 1}</td>
                          <td className={td}>
                            <div className="max-w-[18rem]">
                              <div
                                className={`truncate font-medium ${r.selected ? 'text-neutral-900 dark:text-white' : ''}`}
                                title={it.item_description ?? it.item_name ?? undefined}
                              >
                                {it.item_description ?? it.item_name ?? '—'}
                              </div>
                              {/* PN / material code, always shown at item level. */}
                              <span
                                className="mt-1 inline-flex max-w-full items-center truncate rounded-md bg-[#E1E4F8] px-1.5 py-0.5 font-mono text-[11px] font-medium text-[#5166AE] dark:bg-[#5166AE]/25 dark:text-[#c7cff0]"
                                title="PN / Material Code"
                              >
                                PN · {it.material_code ?? it.item_name ?? 'unmatched'}
                              </span>
                            </div>
                          </td>
                          <td className={`${td} text-neutral-600 dark:text-slate-300`}>{it.uom ?? '-'}</td>
                          <td className={`${td} text-right font-semibold tabular-nums text-neutral-800 dark:text-slate-100`}>
                            {fmt(it.qty_remaining)}
                          </td>
                          <td className={td}>
                            <input
                              type="number"
                              step="any"
                              min={0}
                              max={it.qty_remaining}
                              disabled={!r.selected}
                              aria-invalid={over}
                              className={`input w-full text-right text-sm tabular-nums disabled:cursor-not-allowed disabled:bg-neutral-100 ${
                                r.selected && over ? 'border-red-400 focus:border-red-500 focus:ring-red-500/30' : ''
                              }`}
                              value={r.plannedQty}
                              onChange={(e) => patch(it.id, { plannedQty: Number(e.target.value) })}
                            />
                          </td>
                          <td className={td}>
                            <SearchableSelect
                              value={r.binId}
                              disabled={!r.selected}
                              onChange={(v) => patch(it.id, { binId: v })}
                              placeholder={loadingOptions ? 'Loading…' : 'Select bin…'}
                              searchPlaceholder="Search bin…"
                              options={binOptions}
                            />
                          </td>
                          <td className={td}>
                            <SearchableSelect
                              value={r.pickerId}
                              disabled={!r.selected}
                              onChange={(v) => patch(it.id, { pickerId: v })}
                              placeholder="Select picker…"
                              searchPlaceholder="Search picker…"
                              options={pickerOptions}
                            />
                          </td>
                        </tr>
                      );
                    })}
                  </tbody>
                </table>
              </div>
            )}
          </section>
        </div>

        {/* Footer */}
        <div className="flex shrink-0 flex-wrap items-center justify-between gap-3 border-t border-neutral-200 bg-neutral-50/60 px-6 py-4 dark:border-slate-700 dark:bg-slate-900/40">
          <p className={`text-xs ${missingBin && selected.length > 0 ? 'font-medium text-red-600' : 'text-neutral-500'}`}>
            {selected.length === 0
              ? 'Tick the materials to put away.'
              : missingBin
                ? '*Please select Destination Bin for all selected materials.'
                : `${selected.length} material(s) · ${fmt(totalPlanned)} qty planned for putaway`}
          </p>
          <div className="flex gap-2">
            <button type="button" className="btn-secondary" onClick={onClose} disabled={submitting}>
              Cancel
            </button>
            <button
              type="button"
              className="inline-flex items-center gap-2 rounded-lg bg-[#5166AE] px-5 py-2 text-sm font-semibold text-white shadow-sm transition hover:bg-[#43579a] disabled:cursor-not-allowed disabled:opacity-50"
              onClick={submit}
              disabled={submitting || selected.length === 0 || missingBin}
            >
              {submitting ? 'Generating…' : 'Generate Putaway'}
            </button>
          </div>
        </div>
      </div>
    </div>
  );
}
