import type { ReactNode } from 'react';

/** Building blocks shared by the Sales Delivery and Sales Return create forms. */

export function FieldLabel({
  children,
  required,
  aside,
}: {
  children: ReactNode;
  required?: boolean;
  aside?: string;
}) {
  return (
    <div className="mb-1.5 flex items-baseline justify-between gap-2">
      <span className="text-sm font-medium text-slate-700">
        {children}
        {required && <span className="ml-0.5 text-rose-500">*</span>}
      </span>
      {aside && <span className="text-xs text-slate-400">{aside}</span>}
    </div>
  );
}

export const DOC_NUMBER_MAX = 100;

/**
 * Document number with the "System Format / Manual Input" toggle. Off, the
 * number is generated on submit; on, the user types it (unique, max 100).
 */
export function DocNumberField({
  label,
  manual,
  value,
  onManualChange,
  onChange,
}: {
  label: string;
  manual: boolean;
  value: string;
  onManualChange: (manual: boolean) => void;
  onChange: (value: string) => void;
}) {
  return (
    <div>
      <FieldLabel required={manual} aside={manual ? `${value.length}/${DOC_NUMBER_MAX}` : undefined}>
        {label}
      </FieldLabel>
      {manual ? (
        <input
          className="input"
          value={value}
          maxLength={DOC_NUMBER_MAX}
          onChange={(e) => onChange(e.target.value)}
          placeholder={`Enter ${label} (max ${DOC_NUMBER_MAX} chars)…`}
        />
      ) : (
        <div className="input cursor-not-allowed bg-slate-100 text-slate-400">
          Generated by System
        </div>
      )}
      <label className="mt-2 inline-flex cursor-pointer items-center gap-2 text-xs">
        <span className={manual ? 'text-slate-400' : 'font-medium text-slate-700'}>
          System Format
        </span>
        <button
          type="button"
          role="switch"
          aria-checked={manual}
          aria-label={`Manual ${label}`}
          onClick={() => onManualChange(!manual)}
          className={`relative h-5 w-9 rounded-full transition-colors ${
            manual ? 'bg-brand-600' : 'bg-slate-300'
          }`}
        >
          <span
            className={`absolute top-0.5 h-4 w-4 rounded-full bg-white shadow transition-all ${
              manual ? 'left-[18px]' : 'left-0.5'
            }`}
          />
        </button>
        <span className={manual ? 'font-medium text-slate-700' : 'text-slate-400'}>
          Manual Input
        </span>
      </label>
    </div>
  );
}

/** A value the user cannot change, laid out like an input. */
export function ReadOnlyField({ children }: { children: ReactNode }) {
  return (
    <div className="input cursor-not-allowed truncate bg-slate-100 text-slate-600">
      {children}
    </div>
  );
}

