/** Shared pager under a card grid: page size, range, and page buttons. */
export function GridPager({
  pageSize,
  pageSizes,
  onPageSize,
  start,
  shown,
  total,
  page,
  pageCount,
  onPage,
}: {
  pageSize: number;
  pageSizes: number[];
  onPageSize: (n: number) => void;
  start: number;
  shown: number;
  total: number;
  page: number;
  pageCount: number;
  onPage: (p: number) => void;
}) {
  return (
    <div className="flex flex-wrap items-center justify-between gap-3 rounded-lg border border-slate-200 px-3 py-2 text-xs text-slate-500">
      <div className="flex items-center gap-2">
        <span>Showing</span>
        <select
          className="input w-auto py-1 text-xs"
          value={pageSize}
          onChange={(e) => onPageSize(Number(e.target.value))}
        >
          {pageSizes.map((n) => (
            <option key={n} value={n}>
              {n}
            </option>
          ))}
        </select>
        <span>Data</span>
        <span className="text-slate-300">|</span>
        <span>
          <b className="text-slate-700">
            {total === 0 ? 0 : start + 1}-{start + shown}
          </b>{' '}
          of <b className="text-slate-700">{total}</b>
        </span>
      </div>
      <div className="flex items-center gap-1">
        <button
          type="button"
          className="rounded px-2 py-1 hover:bg-slate-100 disabled:text-slate-300 disabled:hover:bg-transparent"
          disabled={page <= 1}
          onClick={() => onPage(page - 1)}
        >
          ‹ Previous
        </button>
        {Array.from({ length: pageCount }, (_, i) => i + 1).map((p) => (
          <button
            key={p}
            type="button"
            className={`min-w-[26px] rounded border px-1.5 py-1 ${
              p === page
                ? 'border-slate-300 bg-white font-semibold text-slate-800'
                : 'border-transparent hover:bg-slate-100'
            }`}
            onClick={() => onPage(p)}
          >
            {p}
          </button>
        ))}
        <button
          type="button"
          className="rounded px-2 py-1 hover:bg-slate-100 disabled:text-slate-300 disabled:hover:bg-transparent"
          disabled={page >= pageCount}
          onClick={() => onPage(page + 1)}
        >
          Next ›
        </button>
      </div>
    </div>
  );
}
